"""Refresh a separate image cache so file:// export can embed local images.

Usage: python scripts/embed-assets.py [path/to/template.html]
Uses only Python's standard library. Keeps visible img src paths readable.
"""
from __future__ import annotations

import base64
from html import unescape
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import sys


class ImageSources(HTMLParser):
    def __init__(self):
        super().__init__()
        self.sources: set[str] = set()

    def handle_starttag(self, tag, attrs):
        if tag != "img":
            return
        source = dict(attrs).get("src", "")
        if source and not source.startswith(("data:", "http:", "https:", "//")):
            self.sources.add(unescape(source))


def refresh(target: Path) -> int:
    target = target.resolve()
    root = target.parent
    original = target.read_text(encoding="utf-8")
    parser = ImageSources()
    parser.feed(original)
    cache = {}
    mime = {".svg": "image/svg+xml", ".png": "image/png", ".jpg": "image/jpeg",
            ".jpeg": "image/jpeg", ".webp": "image/webp", ".gif": "image/gif"}
    for source in sorted(parser.sources):
        asset = (root / source).resolve()
        if not asset.is_relative_to(root):
            raise ValueError(f"Image must be inside the template directory: {source}")
        if asset.suffix.lower() not in mime:
            raise ValueError(f"Unsupported image format: {source}")
        encoded = base64.b64encode(asset.read_bytes()).decode("ascii")
        cache[source] = f"data:{mime[asset.suffix.lower()]};base64,{encoded}"
    payload = json.dumps(cache, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
    cache_dir = root / "assets"
    cache_file = cache_dir / (target.stem + ".embedded.js")
    cache_text = "// Generated by scripts/embed-assets.py. Do not edit by hand.\nwindow.LNTU_ASSET_CACHE=" + payload + ";\n"
    script_src = "assets/" + cache_file.name
    from html import escape
    block = ('<!-- embedded-assets:start (generated by scripts/embed-assets.py) -->\n'
             '<script id="embedded-assets" src="' + escape(script_src, quote=True) + '"></script>\n'
             '<!-- embedded-assets:end -->\n')
    pattern = r'<!-- embedded-assets:start.*?<!-- embedded-assets:end -->\n?'
    clean, count = re.subn(pattern, "", original, flags=re.DOTALL)
    if count > 1:
        raise ValueError("Duplicate asset caches")
    marker = "<script>\n'use strict';"
    if clean.count(marker) != 1:
        raise ValueError("Could not identify the template's main script")
    updated = clean.replace(marker, block + marker, 1)
    cache_dir.mkdir(exist_ok=True)
    if not cache_file.exists() or cache_file.read_text(encoding="utf-8") != cache_text:
        cache_file.write_text(cache_text, encoding="utf-8", newline="\n")
    if updated != original:
        target.write_text(updated, encoding="utf-8", newline="\n")
    return len(cache)


if __name__ == "__main__":
    template = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "template.html"
    print(f"Embedded {refresh(template)} local image assets in {template.name}")
